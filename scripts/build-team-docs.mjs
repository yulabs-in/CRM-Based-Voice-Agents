function findBrowser() {
  const c = [
    process.env.CHROME_PATH,
    "C:/Program Files/Google/Chrome/Application/chrome.exe",
    "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe",
    "C:/Program Files/Microsoft/Edge/Application/msedge.exe",
    "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
    "/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge",
    "/usr/bin/google-chrome", "/usr/bin/chromium", "/usr/bin/chromium-browser", "/usr/bin/microsoft-edge",
  ].filter(Boolean);
  return c.find((x) => existsSync(x));
}

function printPdf(html, outPdf, title) {
  const browser = findBrowser();
  if (!browser) throw new Error("No Edge/Chrome found. Set CHROME_PATH or run with --no-pdf.");
  const dir = mkdtempSync(path.join(tmpdir(), "team-docs-"));
  try {
    const htmlFile = path.join(dir, "guide.html");
    writeFileSync(htmlFile, `<!doctype html><html><head><meta charset="utf-8"><title>${esc(title)}</title><style>${CSS}</style></head><body>${html}</body></html>`);
    execFileSync(browser, [
      "--headless=new", "--disable-gpu", "--no-first-run", "--no-default-browser-check",
      `--user-data-dir=${path.join(dir, "profile")}`, "--no-pdf-header-footer",
      `--print-to-pdf=${outPdf}`, pathToFileURL(htmlFile).href,
    ], { stdio: "pipe", timeout: 120000 });
  } finally {
    try { rmSync(dir, { recursive: true, force: true }); } catch {}
  }
  if (!existsSync(outPdf)) throw new Error(`PDF not written: ${outPdf}`);
}

// ---------- run ----------
const noPdf = process.argv.includes("--no-pdf");
mkdirSync(p("docs/team/pdf"), { recursive: true });
for (const m of MEMBERS) {
  const md = buildMarkdown(m);
  const mdFile = p("docs/team", `${m.slug}.md`);
  writeFileSync(mdFile, md);
  console.log("wrote", path.relative(root, mdFile));
  if (!noPdf) {
    const pdf = p("docs/team/pdf", `${m.name.replace(/\s+/g, "-")}-Developer-Guide.pdf`);
    printPdf(mdToHtml(md), pdf, `Developer guide: ${m.name}`);
    console.log("wrote", path.relative(root, pdf));
  }
}
