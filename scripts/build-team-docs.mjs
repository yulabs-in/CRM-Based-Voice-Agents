#!/usr/bin/env node
// Builds one developer guide per team member from:
//   docs/team/templates/guide.md          shared workflow (setup, git, testing, PRs into dev)
//   docs/team/templates/plan-<login>.md   the member's order of work and collaborators
//   docs/issues/<nn>-<name>/README.md     full per-issue README, copied in for the member's issues
//                                         (falls back to the "## #N: Title" summary in docs/issues/README.md)
// Writes docs/team/<slug>.md and docs/team/pdf/<Name>-Developer-Guide.pdf (PDF via headless Chrome/Edge).
//
//   node scripts/build-team-docs.mjs            # markdown + PDFs
//   node scripts/build-team-docs.mjs --no-pdf   # markdown only

import { readFileSync, writeFileSync, mkdirSync, existsSync, mkdtempSync, rmSync, readdirSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const p = (...s) => path.join(root, ...s);

const MEMBERS = [
  { login: "KAMMAR-SHASHANK", name: "Kammar Shashank", slug: "kammar-shashank", issues: [4, 10, 16, 13, 19, 22, 25, 7] },
  { login: "Tejaswini2706", name: "Tejaswini", slug: "tejaswini", issues: [18, 9, 6, 12, 15, 21, 24] },
  { login: "CHARANVARIGONDA", name: "Charan Varigonda", slug: "charan-varigonda", issues: [5, 14, 11, 17, 20, 23, 8] },
];

// ---------- issue sections ----------
const issuesMd = readFileSync(p("docs/issues/README.md"), "utf8");
const sections = new Map();
{
  const re = /^## #(\d+): (.+)$/gm;
  const hits = [...issuesMd.matchAll(re)];
  hits.forEach((m, i) => {
    const end = i + 1 < hits.length ? hits[i + 1].index : issuesMd.length;
    const body = issuesMd.slice(m.index, end).trim();
    const branch = (body.match(/\*\*Branch:\*\* `([^`]+)`/) || [])[1] || "";
    sections.set(Number(m[1]), { title: m[2].trim(), body, branch });
  });
}

// Detailed per-issue READMEs (docs/issues/04-profile-page/README.md …) override the summaries above.
const demote = (md) => {
  let fence = false;
  return md.split(/\r?\n/).map((l) => {
    if (/^\s*```/.test(l)) fence = !fence;
    return !fence && /^#{1,5}\s/.test(l) ? "#" + l : l;
  }).join("\n");
};
for (const dir of readdirSync(p("docs/issues"), { withFileTypes: true })) {
  const m = dir.isDirectory() && dir.name.match(/^(\d+)-/);
  const file = m && p("docs/issues", dir.name, "README.md");
  if (!file || !existsSync(file)) continue;
  const md = readFileSync(file, "utf8").trim();
  const head = md.match(/^# #(\d+): (.+)$/m);
  const branchRow = md.match(/\| \*\*Branch\*\* \|[^`]*`([^`]+)`/);
  if (!head) continue;
  const n = Number(head[1]);
  sections.set(n, { title: head[2].trim(), body: demote(md), branch: branchRow ? branchRow[1] : sections.get(n)?.branch || "" });
}

const today = new Date().toISOString().slice(0, 10);
const template = readFileSync(p("docs/team/templates/guide.md"), "utf8");

function buildMarkdown(m) {
  const missing = m.issues.filter((n) => !sections.has(n));
  if (missing.length) throw new Error(`No section for issue(s) ${missing.join(", ")} in docs/issues/README.md`);
  const first = m.issues[0];
  const firstBranch = sections.get(first).branch.replace(/^feature\//, "").split(" ")[0];
  const table = [
    "| Order | Issue | Title | Branch |",
    "|---|---|---|---|",
    ...m.issues.map((n, i) => {
      const s = sections.get(n);
      return `| ${i + 1} | [#${n}](https://github.com/yulabs-in/CRM-Based-Voice-Agents/issues/${n}) | ${s.title} | \`${s.branch}\` |`;
    }),
  ].join("\n");
  const plan = readFileSync(p(`docs/team/templates/plan-${m.login}.md`), "utf8").trim();
  const issues = m.issues.map((n) => sections.get(n).body).join("\n\n---\n\n");
  const vars = { NAME: m.name, LOGIN: m.login, DATE: today, FIRST: String(first), FIRST_BRANCH_SHORT: firstBranch, ISSUE_TABLE: table, PLAN: plan, ISSUES: issues };
  const md = template.replace(/\{\{(\w+)\}\}/g, (_, k) => {
    if (!(k in vars)) throw new Error(`Unknown placeholder {{${k}}}`);
    return vars[k];
  });
  return `<!-- Generated by scripts/build-team-docs.mjs. Edit docs/team/templates/* or docs/issues/README.md, then re-run. -->\n\n${md}`;
}

// ---------- tiny markdown → HTML (headings, lists, tables, code, quotes, inline) ----------
const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
function inline(s) {
  const codes = [];
  s = s.replace(/`([^`]+)`/g, (_, c) => `\u0000${codes.push(esc(c)) - 1}\u0000`);
  s = esc(s);
  s = s.replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (_, t, u) => `<a href="${u}">${t}</a>`);
  s = s.replace(/(^|[\s(])(https?:\/\/[^\s<)]+[^\s<).,;:])/g, (_, pre, u) => `${pre}<a href="${u}">${u}</a>`);
  s = s.replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>");
  s = s.replace(/(^|[\s(])\*([^*\s][^*]*)\*/g, "$1<em>$2</em>");
  s = s.replace(/\u0000(\d+)\u0000/g, (_, i) => `<code>${codes[i]}</code>`);
  return s;
}
function mdToHtml(md) {
  md = md.replace(/<!--[\s\S]*?-->/g, "");
  const lines = md.split(/\r?\n/);
  const out = [];
  const lists = []; // stack of { type, indent }
  let para = [];
  let issueCount = 0;
  const flushPara = () => { if (para.length) { out.push(`<p>${inline(para.join(" "))}</p>`); para = []; } };
  const closeLists = (toIndent = -1) => {
    while (lists.length && lists[lists.length - 1].indent > toIndent) out.push(`</li></${lists.pop().type}>`);
  };
  let i = 0;
  while (i < lines.length) {
    const line = lines[i];
    const fence = line.match(/^(\s*)```(\w*)\s*$/);
    if (fence) {
      flushPara();
      const ind = fence[1].length;
      if (ind === 0) closeLists();
      const buf = [];
      i++;
      while (i < lines.length && !/^\s*```\s*$/.test(lines[i])) { buf.push(lines[i].slice(Math.min(ind, lines[i].search(/\S|$/)))); i++; }
      i++;
      out.push(`<pre><code>${esc(buf.join("\n"))}</code></pre>`);
      continue;
    }
    if (/^\s*$/.test(line)) { flushPara(); i++; continue; }
    const h = line.match(/^(#{1,6})\s+(.*)$/);
    if (h) {
      flushPara(); closeLists();
      const lvl = h[1].length;
      const id = h[2].toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
      const isIssue = lvl === 2 && /^#\d+:/.test(h[2]);
      const cls = isIssue ? (issueCount++ ? ' class="issue"' : ' class="issue first"') : "";
      out.push(`<h${lvl}${cls} id="${id}">${inline(h[2])}</h${lvl}>`);
      i++; continue;
    }
    if (/^\s*---+\s*$/.test(line)) { flushPara(); closeLists(); out.push("<hr>"); i++; continue; }
    if (/^\s*\|/.test(line) && i + 1 < lines.length && /^\s*\|?\s*:?-{3,}/.test(lines[i + 1])) {
      flushPara(); closeLists();
      const cells = (l) => l.trim().replace(/^\||\|$/g, "").split(/(?<!\\)\|/).map((c) => inline(c.trim()));
      const head = cells(line);
      i += 2;
      const rows = [];
      while (i < lines.length && /^\s*\|/.test(lines[i])) { rows.push(cells(lines[i])); i++; }
      const thead = head.every((c) => !c) ? "" : `<thead><tr>${head.map((c) => `<th>${c}</th>`).join("")}</tr></thead>`;
      out.push(`<table>${thead}<tbody>${rows.map((r) => `<tr>${r.map((c) => `<td>${c}</td>`).join("")}</tr>`).join("")}</tbody></table>`);
      continue;
    }
    if (/^>\s?/.test(line)) {
      flushPara(); closeLists();
      const buf = [];
      while (i < lines.length && /^>\s?/.test(lines[i])) { buf.push(lines[i].replace(/^>\s?/, "")); i++; }
      out.push(`<blockquote>${mdToHtml(buf.join("\n"))}</blockquote>`);
      continue;
    }
    const li = line.match(/^(\s*)([-*]|\d+\.)\s+(.*)$/);
    if (li) {
      flushPara();
      const indent = li[1].length;
      const type = /\d/.test(li[2]) ? "ol" : "ul";
      let text = li[3];
      const top = lists[lists.length - 1];
      if (!top || indent > top.indent) {
        const start = type === "ol" && parseInt(li[2]) !== 1 ? ` start="${parseInt(li[2])}"` : "";
        out.push(`<${type}${start}>`);
        lists.push({ type, indent });
      } else {
        closeLists(indent);
        const cur = lists[lists.length - 1];
        if (cur && cur.indent === indent && cur.type !== type) { out.push(`</li></${lists.pop().type}>`); }
        if (!lists.length || lists[lists.length - 1].indent < indent || lists[lists.length - 1].type !== type) {
          out.push(`<${type}>`); lists.push({ type, indent });
        } else out.push("</li>");
      }
      const box = text.match(/^\[( |x)\]\s+(.*)$/i);
      if (box) text = `<span class="box">${box[1].trim() ? "☑" : "☐"}</span> ${inline(box[2])}`;
      else text = inline(text);
      out.push(box ? `<li class="task">${text}` : `<li>${text}`);
      i++;
      // lazy continuation lines (indented text that isn't a new item or fence)
      while (i < lines.length && /^\s{2,}\S/.test(lines[i]) && !/^\s*([-*]|\d+\.)\s+/.test(lines[i]) && !/^\s*```/.test(lines[i])) {
        out.push(" " + inline(lines[i].trim())); i++;
      }
      continue;
    }
    if (lists.length && /^\s+\S/.test(line)) { out.push(" " + inline(line.trim())); i++; continue; }
    closeLists();
    para.push(line.trim());
    i++;
  }
  flushPara(); closeLists();
  return out.join("\n");
}

